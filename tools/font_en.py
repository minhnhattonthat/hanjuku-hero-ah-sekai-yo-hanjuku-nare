"""English 8x8 font for the game's 2bpp text tiles (plane 0 = FF, plane 1 = glyph -> colour 3 on colour 1).

GLYPHS maps a character to 8 rows of 8 pixels ('#' = ink). Codes come from tbl/en.tbl (tools/mktbl.py).
"""

