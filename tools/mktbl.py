"""Generate tbl/jp.tbl (kana glyph rows from the 8x8 font at ROM 0xE6000; text codes C4+ = dakuten/handakuten kana).

Control codes are appended from CTRL below (filled in from RE, docs/re/text.md)."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ROWS = {
    0x3C: "”♪♥〜",
    0x40: "ハはヒひフふヘへホほカかキきクく",
    0x50: "ケけコこサさシしスすセせソそタた",
    0x60: "チちツつテてトとウうアあイいエえ",
    0x70: "オおナなニにヌぬネねノのマまミみ",
    0x80: "ムむメめモもラらリりルるレれロろ",
    0x90: "ヤやユゆヨよワわンんヲをッっャゃ",
    0xA0: "ュゅョょァーィ‥ゥ！ェ？ォ：「」",
    0xB0: "。ＡＢＸＹＬＲＨＰＧ０１２３４５",
    0xC0: "６７８９",
}
VOICED = "バばビびブぶベべボぼガがギぎグぐゲげゴごザざジじズずゼぜゾぞダだヂぢヅづデでドどヴパぱピぴプぷペぺポぽ"  # C4-EC: glyph code-0x84 + dakuten; ED-F6: code-0xAD + handakuten ($04:92BC)
CTRL = {}


def lines():
    out = ["# generated by tools/mktbl.py"]
    for base, row in ROWS.items():
        for i, ch in enumerate(row):
            out.append(f"{base + i:02X}={ch}")
    for i, ch in enumerate(VOICED):
        out.append(f"{0xC4 + i:02X}={ch}")
    out.append("FF=　")
    for code, val in CTRL.items():
        out.append(f"{code}={val}")
    return out


EN_PUNCT = ".,'!?-:;()/&+%…*#=<>é"
EN = {0x3C: '"', 0x3D: "♪", 0x3E: "♥", 0x3F: "~", 0xFF: " "}
for _i in range(26):
    EN[0x40 + _i] = chr(65 + _i)
    EN[0x5A + _i] = chr(97 + _i)
for _i, _c in enumerate(EN_PUNCT):
    EN[0x74 + _i] = _c
for _i in range(10):
    EN[0xBA + _i] = str(_i)
EN_FIRST_FREE = 0x74 + len(EN_PUNCT)  # 0x89: codes from here to 0xB9 are free for extra glyphs


def en_lines():
    out = ["# generated by tools/mktbl.py (English)"]
    for code, ch in sorted(EN.items()):
        out.append(f"{code:02X}=" + ("\\s" if ch == " " else ch))
    return out


if __name__ == "__main__":
    (ROOT / "tbl" / "jp.tbl").write_text("\n".join(lines()) + "\n", encoding="utf-8", newline="\n")
    (ROOT / "tbl" / "en.tbl").write_text("\n".join(en_lines()) + "\n", encoding="utf-8", newline="\n")
